import Foundation

let unavailable = BackstageStatusPresentation.summary(status: "not_connected", claimedAtMS: nil)
assert(unavailable.contains("暂无本场复盘") && unavailable.contains("后续状态以服务端回报为准"))
assert(!unavailable.contains("不自动补领"))
assert(!unavailable.contains("待处理") && !unavailable.contains("离线") && !unavailable.contains("繁忙"))
let waiting = BackstageStatusPresentation.summary(status: "waiting_for_stop", claimedAtMS: nil)
assert(waiting.contains("已登记") && waiting.contains("待确认") && !waiting.contains("已绑定"))
let claimed = BackstageStatusPresentation.summary(status: "waiting_for_stop", claimedAtMS: 123)
assert(claimed.contains("已领取") && !claimed.contains("直播间"))
let capturing = BackstageStatusPresentation.summary(status: "capturing", claimedAtMS: 123)
assert(capturing.contains("已领取") && capturing.contains("等待本场结果"))
assert(BackstageStatusPresentation.summary(status: "failed", claimedAtMS: 123).contains("失败"))
assert(BackstageStatusPresentation.summary(status: "captured_locally", claimedAtMS: 123, receivedMetricCount: 5).contains("已收到"))
assert(BackstageStatusPresentation.summary(status: "captured_locally", claimedAtMS: 123).contains("待确认"))
assert(BackstageStatusPresentation.summary(status: "captured_locally", claimedAtMS: 123, receivedMetricCount: 4).contains("待确认"))
assert(BackstageStatusPresentation.summary(status: "needs_input", claimedAtMS: 123).contains("需要"))
assert(BackstageStatusPresentation.summary(status: "partial", claimedAtMS: 123, receivedMetricCount: 3).contains("部分缺失"))
assert(BackstageStatusPresentation.summary(status: "partial", claimedAtMS: 123).contains("尚未取得"))
assert(BackstageStatusPresentation.summary(status: "not_connected", claimedAtMS: 123).contains("后续状态以服务端回报为准"))
assert(BackstageStatusPresentation.summary(status: "unknown", claimedAtMS: nil).contains("待确认"))
let active = BackstageStatusPresentation.active(status: "not_connected")
assert(active.contains("实时场次已创建") && active.contains("暂无本场复盘"))
assert(BackstageStatusPresentation.active(status: "waiting_for_stop").contains("取数状态待确认"))
assert(BackstageStatusPresentation.active(status: "captured_locally").contains("待确认"))
assert(BackstageStatusPresentation.recovered(status: "not_connected").contains("后续状态以服务端回报为准"))
assert(!BackstageStatusPresentation.acceptsStartCallback(generation: 1, currentGeneration: 2, starting: true, stopping: false))
assert(!BackstageStatusPresentation.acceptsStartCallback(generation: 1, currentGeneration: 1, starting: false, stopping: false))
assert(!BackstageStatusPresentation.acceptsStartCallback(generation: 1, currentGeneration: 1, starting: true, stopping: true))
assert(BackstageStatusPresentation.acceptsStartCallback(generation: 2, currentGeneration: 2, starting: true, stopping: false))
print("OK: backstage status distinguishes unavailable, registered, claimed and results")
